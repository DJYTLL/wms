      remark: formData.remark,
      items: validItems.map((item, index) => {
        ensureStockBinding(item);
        return {
          productId: item.productId,
          warehouseId: item.warehouseId,
          locationId: item.locationId,
          qty: parseDecimal(item.qty, 4),
          price: parseDecimal(item.price, 4),
          taxRate: item.taxRate,
          remark: item.remark,
          sortNo: index + 1
        };
      })
    };

  try {
    const res: any = isEditing.value
      ? await request.put(`/erp/sale-returns/${route.params.id}`, payload)
      : await request.post('/erp/sale-returns', payload);

    if (res.data.code === 200) {
      const data = res.data.data || {};
      const savedId = data.order?.id || data.id || Number(route.params.id || 0) || null;
      notifySuccess();
      if (!isEditing.value && savedId && options.reloadAfterCreate) {
        await router.replace(`/erp/sale-returns/${savedId}/edit`);
        await loadDetail();
      }
      if (closeOnSuccess) {
        closePage();
        await router.push('/erp/sale-returns/draft');
      }
      return savedId;
    }
  } catch (error) {
    notifyError(error);
  }
  return null;
};

const parseDecimal = (value: string | number | undefined, scale: number) => {
  if (value == null || value === '') return 0;
  const raw = String(value);
  const normalized = raw.endsWith('.') ? raw.slice(0, -1) : raw;
  if (!normalized) return 0;
  const regex = new RegExp(`^\\d+(\\.\\d{1,${scale}})?$`);
  if (!regex.test(normalized)) {
    return null;
  }
  return Number(normalized);
};

const parseAmount = (value: string) => parseDecimal(value, 2);

const formatDateTime = (date: Date) => {
  const pad = (num: number) => String(num).padStart(2, '0');
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
};

const normalizeDateTimeValue = (value: any) => {
  if (!value) return '';
  if (value instanceof Date) {
    return formatDateTime(value);
  }
  const raw = String(value);
  if (!raw) return '';
  if (raw.includes('T')) {
    const parsed = new Date(raw);
    if (Number.isNaN(parsed.getTime())) {
      return '';
    }
    return formatDateTime(parsed);
  }
  return raw;
};

const handleTagClosing = (event: Event) => {
  const customEvent = event as CustomEvent<{ path?: string }>;
  if (customEvent.detail?.path === pagePath.value) {
    needsReload.value = true;
    resetForm();
  }
};

watch(
  () => route.fullPath,
  (newPath) => {
    if (newPath === lastRouteKey.value) return;
    lastRouteKey.value = newPath;
    pagePath.value = route.path;
    loadDetail();
  }
);

onMounted(() => {
  pagePath.value = route.path;
  fetchCustomers();
  fetchSaleOrders();
  fetchProducts();
  fetchWarehouses();
  fetchLocations();
  fetchSettlementMethods();
  loadDetail();
  if (typeof window !== 'undefined') {
    window.addEventListener('tags:closing', handleTagClosing as EventListener);
    window.addEventListener('tags:close', handleTagClosing as EventListener);
    window.addEventListener('keydown', handleKeydown);
  }
});

onActivated(() => {
  if (!needsReload.value) return;
  needsReload.value = false;
  loadDetail();
});

onBeforeUnmount(() => {
  if (typeof window !== 'undefined') {
    window.removeEventListener('tags:closing', handleTagClosing as EventListener);
    window.removeEventListener('tags:close', handleTagClosing as EventListener);
    window.removeEventListener('keydown', handleKeydown);
  }
  resetForm();
});
