<script setup lang="ts">
import { computed, onMounted, onBeforeUnmount, onActivated, reactive, ref, watch } from 'vue';
import { useI18n } from 'vue-i18n';
import { useRoute, useRouter } from 'vue-router';
import request from '@/utils/request';
import { useApiError } from '@/composables/useApiError';
import DecimalInput from '@/components/DecimalInput.vue';
import FuzzyProductSelect from '@/components/FuzzyProductSelect.vue';
import PrintPreviewDialog from '@/components/PrintPreviewDialog.vue';
import { ElMessageBox } from 'element-plus';
import { useAuthStore } from '@/stores/auth';

interface OptionItem {
  id: number;
  name: string;
  warehouseId?: number;
  categoryId?: number;
  paymentTerms?: string;
}

interface SaleOrderOption {
  id: number;
  orderNo: string;
  customerId?: number;
}

interface SaleOrderDetailItem {
  id?: number;
  productId?: number;
  productCode?: string;
  productName?: string;
  warehouseId?: number;
  locationId?: number;
  qty?: number;
  price?: number;
  taxRate?: number;
}

interface ProductOption {
  id: number;
  name: string;
  defaultWarehouseId?: number;
  defaultLocationId?: number;
  salePrice?: number;
  costPrice?: number;
}

interface RecentSaleItem {
  orderId: number;
  orderNo: string;
  orderAt?: string;
  productId: number;
  qty: number;
  price: number;
}

interface StockOption {
  key: string;
  warehouseId: number | null;
  warehouseName: string;
  locationId: number | null;
  locationName: string;
  qtyOnHand: number;
  qtyAvailable: number;
  qtyLocked: number;
  label: string;
  searchLabel: string;
}

interface CodeOptionItem {
  id: number;
  code: string;
  name: string;
  isDefault?: boolean;
}

interface SaleReturnItem {
  id?: number;
  productId?: number;
  warehouseId?: number;
  locationId?: number;
  stockKey?: string;
  qty?: string | number;
  price?: string | number;
  taxRate?: number;
  remark?: string;
  sortNo?: number;
}

const { t } = useI18n();
const router = useRouter();
const route = useRoute();
const { notifyError, notifySuccess, notifyWarning } = useApiError();
const authStore = useAuthStore();

const isEditing = computed(() => Boolean(route.params.id));
const isReadOnly = computed(() => {
  if (route.query.mode === 'view') return true;
  if (!formData.status) return false;
  return formData.status !== 'DRAFT';
});

const canCopy = computed(() => {
  return isReadOnly.value
    && (formData.status === 'APPROVED' || formData.status === 'RED_FLUSHED')
    && hasPermission('erp-sale-return:add');
});

const canPrint = computed(() => {
  return isEditing.value && hasPermission('erp-sale-return:view');
});

const canRedFlush = computed(() => {
  return isReadOnly.value && formData.status === 'APPROVED' && hasPermission('erp-sale-return:redflush');
});

const pageTitle = computed(() => (isEditing.value ? t('page.erpSaleReturnEdit') : t('page.erpSaleReturnCreate')));
const themeMode = ref<'default' | 'paper'>('default');

const customerOptions = ref<OptionItem[]>([]);
const saleOrderOptions = ref<SaleOrderOption[]>([]);
const productOptions = ref<ProductOption[]>([]);
const warehouseOptions = ref<OptionItem[]>([]);
const locationOptions = ref<OptionItem[]>([]);
const settlementMethodOptions = ref<CodeOptionItem[]>([]);
const productStockMap = ref<Record<number, StockOption[]>>({});
const productRecentSalesMap = ref<Record<number, RecentSaleItem[]>>({});
const saleOrderDetailItems = ref<SaleOrderDetailItem[]>([]);
const selectedSaleOrderItems = ref<SaleOrderDetailItem[]>([]);
const showSaleOrderDialog = ref(false);

const formData = reactive({
  orderNo: '',
  orderAt: '',
  status: '',
  returnType: 'RESTOCK',
  returnSource: 'BY_PRODUCT',
  customerId: null as number | null,
  saleOrderId: null as number | null,
  settlementMethod: '',
  paidAmount: '',
  discountAmount: '',
  remark: '',
  items: [] as SaleReturnItem[]
});

const pagePath = ref(route.path);
const lastRouteKey = ref(route.fullPath);
const showCustomerChangeDialog = ref(false);
const pendingCustomerId = ref<number | null>(null);
const lastCustomerId = ref<number | null>(null);
const isInitializing = ref(false);
const needsReload = ref(false);
const showProfitColumn = ref(false);
const printDialogVisible = ref(false);
const printDocId = ref<number | null>(null);

const hasPermission = (code: string) => {
  return authStore.hasPermission(code) || authStore.hasPermission(`PERM_${code}`);
};

const canApprove = computed(() => {
  return !isReadOnly.value && formData.status === 'DRAFT' && hasPermission('erp-sale-return:approve');
});

const canViewProfit = computed(() => {
  return hasPermission('column:erp-sale:profit')
    && (hasPermission('erp-product:cost:view') || hasPermission('erp-product:cost:edit'));
});

const canShowProfit = computed(() => canViewProfit.value && showProfitColumn.value);
const canShowDiscountAllocated = computed(() => hasPermission('column:erp-sale:discountAllocated'));

const isTypingTarget = (target: EventTarget | null) => {
  if (!target || !(target instanceof HTMLElement)) return false;
  const tag = target.tagName.toLowerCase();
  if (tag === 'input' || tag === 'textarea' || tag === 'select') return true;
  return target.isContentEditable;
};

const handleKeydown = (event: KeyboardEvent) => {
  if (!canViewProfit.value) return;
  if (isTypingTarget(event.target)) return;
  if (event.key && event.key.toLowerCase() === 'u') {
    showProfitColumn.value = !showProfitColumn.value;
  }
};

const closePage = () => {
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('tags:close', { detail: { path: route.path } }));
  }
};

const handleBack = async () => {
  if (isEditing.value) {
    resetForm();
    closePage();
    return;
  }

  const hasItems = formData.items.some(item => item.productId);
  if (hasItems) {
    try {
      await ElMessageBox.confirm(
        t('message.confirmSaveDraft'),
        t('action.confirm'),
        {
          confirmButtonText: t('action.save'),
          cancelButtonText: t('action.cancel'),
          type: 'warning'
        }
      );
      await saveData();
    } catch {
      resetForm();
      closePage();
    }
    return;
  }

  try {
    await ElMessageBox.confirm(
      t('message.confirmClosePage'),
      t('action.confirm'),
      {
        confirmButtonText: t('action.confirm'),
        cancelButtonText: t('action.cancel'),
        type: 'warning'
      }
    );
    resetForm();
    closePage();
  } catch {
    return;
  }
};

const handleApprove = async () => {
  if (isReadOnly.value) return;
  try {
    await ElMessageBox.confirm(
      t('message.confirmSaveBeforeApprove'),
      t('action.confirm'),
      {
        confirmButtonText: t('action.save'),
        cancelButtonText: t('action.cancel'),
        type: 'warning'
      }
    );
  } catch {
    return;
  }

  const savedId = await saveData({ closeOnSuccess: false, reloadAfterCreate: true });
  if (!savedId) return;

  try {
    await ElMessageBox.confirm(
      t('message.confirmApprove'),
      t('action.confirm'),
      {
        confirmButtonText: t('action.approve'),
        cancelButtonText: t('action.cancel'),
        type: 'warning'
      }
    );
    await request.post(`/erp/sale-returns/${savedId}/approve`);
    formData.status = 'APPROVED';
    notifySuccess();
    closePage();
    await router.push('/erp/sale-returns/draft');
  } catch (error) {
    if (error && error !== 'cancel' && error !== 'close') {
      notifyError(error);
    }
  }
};

const handleRedFlush = async () => {
  if (!isEditing.value) return;
  try {
    const { value } = await ElMessageBox.prompt(
      t('message.confirmRedFlush'),
      t('action.redFlush'),
      {
        inputPlaceholder: t('placeholder.required'),
        confirmButtonText: t('action.confirm'),
        cancelButtonText: t('action.cancel')
      }
    );
    if (!value || !String(value).trim()) {
      return;
    }
    await request.post(`/erp/sale-returns/${route.params.id}/red-flush`, null, {
      params: { reason: String(value).trim() }
    });
    notifySuccess();
    closePage();
    await router.push('/erp/sale-returns/approved');
  } catch (error) {
    if (error && error !== 'cancel' && error !== 'close') {
      notifyError(error);
    }
  }
};

const handleSave = async () => {
  await saveData({ closeOnSuccess: false });
};

  const handleSaveAndBack = async () => {
    await saveData({ closeOnSuccess: true });
  };

  const parseStockKey = (stockKey?: string) => {
    if (!stockKey) return { warehouseId: undefined, locationId: undefined };
    const [warehouseRaw, locationRaw] = stockKey.split(':');
    const warehouseId = Number(warehouseRaw);
    const locationId = Number(locationRaw);
    return {
      warehouseId: Number.isNaN(warehouseId) || warehouseId === 0 ? undefined : warehouseId,
      locationId: Number.isNaN(locationId) || locationId === 0 ? undefined : locationId
    };
  };

  const ensureStockBinding = (row: SaleReturnItem) => {
    if (!row.stockKey || !row.productId) return;
    const options = productStockMap.value[row.productId] || [];
    const selected = options.find(item => item.key === row.stockKey);
    if (selected) {
      row.warehouseId = selected.warehouseId ?? undefined;
      row.locationId = selected.locationId ?? undefined;
      return;
    }
    const parsed = parseStockKey(row.stockKey);
    if (row.warehouseId == null) {
      row.warehouseId = parsed.warehouseId;
    }
    if (row.locationId == null) {
      row.locationId = parsed.locationId;
    }
  };

  const handleCopy = async () => {
    if (!formData.customerId || !formData.items.length) {
      notifyWarning(t('message.noItems'));
      return;
    }
  try {
    await ElMessageBox.confirm(
      t('message.confirmCopyOrder'),
