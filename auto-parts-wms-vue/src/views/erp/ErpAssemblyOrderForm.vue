      id: detail.id,
      orderNo: detail.orderNo,
      status: detail.status,
      customerId: detail.customerId,
      customerName: detail.customerName,
      orderAt: detail.orderAt
    });
    sourceSaleOrderItems.value = detail.items || [];
  } catch (error) {
    notifyError(error);
  }
};

const handleSourceSaleOrderItemChange = async (itemId?: number | null) => {
  if (!itemId) return;
  const item = sourceSaleOrderItems.value.find(row => row.id === itemId);
  if (!item) return;
  if (formData.finishedProductId && item.productId && Number(formData.finishedProductId) !== Number(item.productId)) {
    notifyWarning('来源销售行商品与当前成品不一致，不能关联到该组装单');
    formData.sourceSaleOrderItemId = null;
    return;
  }
  if (!formData.finishedProductId) {
    formData.finishedProductId = item.productId || null;
    formData.warehouseId = item.warehouseId ?? null;
    formData.locationId = item.locationId ?? null;
  }
  if (parseDecimal(formData.finishedQty) <= 0) {
    formData.finishedQty = String(item.qty ?? '');
  }
  await Promise.all([
    ensureProductOption(formData.finishedProductId),
    ensureWarehouseOption(formData.warehouseId),
    ensureLocationOption(formData.locationId)
  ]);
  if (formData.finishedProductId) {
    await fetchStockOptions(formData.finishedProductId, true);
    syncFinishedStockKey();
  }
};

const ensureProductOption = async (productId?: number | null) => {
  if (!productId || productOptions.value.some(item => item.id === productId)) return;
  try {
    const res: any = await request.get(`/erp/products/${productId}`);
    const product = res.data.data;
    if (product) {
      productOptions.value = mergeOptionById(productOptions.value, {
        id: product.id,
        name: product.name,
        costPrice: product.costPrice,
        defaultWarehouseId: product.defaultWarehouseId,
        defaultLocationId: product.defaultLocationId,
        enabled: product.enabled
      });
      productSearchOptions.value = mergeOptionById(productSearchOptions.value, {
        id: product.id,
        name: product.name,
        costPrice: product.costPrice,
        defaultWarehouseId: product.defaultWarehouseId,
        defaultLocationId: product.defaultLocationId,
        enabled: product.enabled
      });
    }
  } catch (error) {
    notifyError(error);
  }
};

const getSelectableProductOptions = (currentProductId?: number | null) => {
  const options = productSearchOptions.value.filter(item => item.enabled !== false || item.id === currentProductId);
  if (currentProductId != null && !options.some(item => Number(item.id) === Number(currentProductId))) {
    const current = productOptions.value.find(item => Number(item.id) === Number(currentProductId));
    if (current) {
      options.push(current);
    }
  }
  return options;
};

const ensureWarehouseOption = async (warehouseId?: number | null) => {
  if (!warehouseId || warehouseOptions.value.some(item => item.id === warehouseId)) return;
  try {
    const res: any = await request.get(`/erp/warehouses/${warehouseId}`);
    const warehouse = res.data.data;
    if (warehouse) {
      warehouseOptions.value = mergeOptionById(warehouseOptions.value, {
        id: warehouse.id,
        name: warehouse.name
      });
    }
  } catch (error) {
    notifyError(error);
  }
};

const ensureLocationOption = async (locationId?: number | null) => {
  if (!locationId || locationOptions.value.some(item => item.id === locationId)) return;
  try {
    const res: any = await request.get(`/erp/locations/${locationId}`);
    const location = res.data.data;
    if (location) {
      locationOptions.value = mergeOptionById(locationOptions.value, {
        id: location.id,
        name: location.name,
        warehouseId: location.warehouseId
      });
    }
  } catch (error) {
    notifyError(error);
  }
};

const addItem = () => {
  formData.items.push({
    productId: null,
    warehouseId: formData.warehouseId || null,
    locationId: formData.locationId || null,
    stockKey: '',
    qty: '',
    unitCost: 0,
    amount: 0,
    remark: ''
  });
