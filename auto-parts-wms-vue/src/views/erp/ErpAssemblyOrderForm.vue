<template>
  <div class="page-shell">
    <div class="page-header">
      <h2 class="page-title">{{ pageTitle }}</h2>
      <div class="table-toolbar">
        <el-button @click="handleBack">{{ $t('action.back') }}</el-button>
        <el-tag
          v-if="canApprove"
          type="success"
          size="small"
          class="action-tag action-tag--success"
          @click="handleApprove"
        >
          {{ $t('action.approve') }}
        </el-tag>
        <el-button v-if="!isReadOnly" @click="handleSave">{{ $t('action.save') }}</el-button>
        <el-button v-if="!isReadOnly" type="primary" @click="handleSaveAndBack">{{ $t('action.saveAndBack') }}</el-button>
      </div>
    </div>

    <div class="table-card compact-card sale-header-card">
      <div class="table-body sale-header-body">
        <el-form :model="formData" label-position="top" class="sale-form sale-form--compact">
          <div class="form-grid">
            <div class="form-group">
              <el-form-item :label="$t('field.orderNo')">
                <el-input v-model="formData.orderNo" :placeholder="$t('placeholder.autoGenerated')" disabled />
              </el-form-item>
            </div>
            <div class="form-group">
              <el-form-item :label="$t('field.orderTime')">
                <el-date-picker
                  v-model="formData.orderAt"
                  type="datetime"
                  format="YYYY-MM-DD HH:mm:ss"
                  value-format="YYYY-MM-DD HH:mm:ss"
                  class="order-time-picker"
                  style="width: 100%"
                  :clearable="false"
                  :disabled="isReadOnly"
                />
              </el-form-item>
            </div>
            <div class="form-group">
              <el-form-item :label="$t('field.finishedProduct')" required>
                <FuzzyProductSelect
                  v-model="formData.finishedProductId"
                  :options="productOptions"
