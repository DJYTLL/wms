const handleSourceSaleOrderChange = async (saleOrderId?: number | null) => {
  formData.sourceSaleOrderItemId = null;
  sourceSaleOrderItems.value = [];
  if (!saleOrderId) {
    clearSourceSaleOrder();
    return;
  }
