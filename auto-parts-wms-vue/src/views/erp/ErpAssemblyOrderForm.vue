const syncFinishedStockKey = () => {
  if (!formData.finishedProductId) {
    formData.finishedStockKey = '';
    return;
  }
  const options = productStockMap.value[formData.finishedProductId] || [];
  const key = buildStockKey(formData.warehouseId ?? null, formData.locationId ?? null);
  const matched = options.find(item => item.key === key);
  formData.finishedStockKey = matched ? key : (formData.warehouseId || formData.locationId ? key : '');
};

const syncStockKey = (row: AssemblyItem) => {
  if (!row.productId) {
    row.stockKey = '';
    return;
  }
  const options = productStockMap.value[row.productId] || [];
  const key = buildStockKey(row.warehouseId ?? null, row.locationId ?? null);
  const matched = options.find(item => item.key === key);
  row.stockKey = matched ? key : (row.warehouseId || row.locationId ? key : '');
};

const applyFinishedProductDefaults = (force = true) => {
  if (!formData.finishedProductId) return;
  const product = productOptions.value.find(item => item.id === formData.finishedProductId);
  if (!product) return;
  if (product.defaultWarehouseId && (force || !formData.warehouseId)) {
    formData.warehouseId = product.defaultWarehouseId;
  }
  if (product.defaultLocationId && (force || !formData.locationId)) {
    formData.locationId = product.defaultLocationId;
  }
  if (formData.locationId && formData.warehouseId) {
    const location = locationOptions.value.find(item => item.id === formData.locationId);
    if (location && location.warehouseId && location.warehouseId !== formData.warehouseId) {
      formData.locationId = null;
    }
  }
};

const handleFinishedProductChange = async () => {
  formData.warehouseId = null;
  formData.locationId = null;
  formData.finishedStockKey = '';
  applyFinishedProductDefaults(true);
  syncFinishedStockKey();
};

const handleFinishedStockSelectionChange = (payload: { stockKey: string; warehouseId: number | null; locationId: number | null }) => {
  formData.finishedStockKey = payload.stockKey;
  formData.warehouseId = payload.warehouseId;
  formData.locationId = payload.locationId;
};

