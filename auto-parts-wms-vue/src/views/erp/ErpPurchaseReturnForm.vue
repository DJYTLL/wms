  const saveData = async (
    options: {
      closeOnSuccess?: boolean;
      reloadAfterCreate?: boolean;
      silentSuccess?: boolean;
      showPostSaveDialog?: boolean;
    } = {}
  ) => {
    const closeOnSuccess = options.closeOnSuccess !== false;
    if (!formData.supplierId) {
      notifyWarning(requiredFieldMessage(t('field.supplier')));
      return;
    }
    if (!formData.returnType) {
      notifyWarning(requiredFieldMessage(t('field.returnType')));
      return;
    }
    if (!formData.purchaseOrderId) {
      notifyWarning(
        formData.returnSource === 'BY_PRODUCT'
          ? t('message.pickPurchaseOrderFromRecentPurchase')
          : requiredFieldMessage(t('field.sourcePurchaseOrder'))
      );
      return;
    }
    if (!formData.settlementMethod) {
      notifyWarning(requiredFieldMessage(t('field.settlementMethod')));
      return;
    }
    const validItems = formData.items.filter(item => item.productId);
    if (!validItems.length) {
      notifyWarning(t('message.noItems'));
      return;
    }
    for (const [index, item] of validItems.entries()) {
      const rowNumber = index + 1;
      const qtyValue = parseDecimal(item.qty, 4);
      if (qtyValue == null || qtyValue <= 0) {
        notifyWarning(positiveRowFieldMessage(rowNumber, t('field.quantity')));
        return;
      }
      const priceValue = parseDecimal(item.price, 4);
      if (priceValue == null) {
        notifyWarning(invalidRowFieldMessage(rowNumber, t('field.price')));
        return;
      }
    }

    const paidAmount = showRefundPaymentFields.value ? parseAmount(formData.paidAmount) : 0;
    const discountAmount = parseAmount(formData.discountAmount);
    if (paidAmount == null || discountAmount == null) {
      notifyWarning(t('message.invalidNumber'));
      return;
    }

    const payload = {
      orderNo: formData.orderNo || undefined,
      orderAt: formData.orderAt || undefined,
      returnType: formData.returnType || 'RETURN',
      supplierId: formData.supplierId,
      purchaseOrderId: formData.purchaseOrderId || undefined,
      settlementMethod: formData.settlementMethod,
      paymentMethodCode: showRefundPaymentFields.value ? (formData.paymentMethodCode || undefined) : undefined,
      refundAction: formData.refundAction,
      paidAmount,
      discountAmount,
      remark: formData.remark,
      items: validItems.map((item, index) => {
        ensureStockBinding(item);
        return {
          productId: item.productId,
          warehouseId: item.warehouseId,
          locationId: item.locationId,
          qty: parseDecimal(item.qty, 4),
          price: parseDecimal(item.price, 4),
          taxRate: item.taxRate,
          remark: item.remark,
          sortNo: index + 1
        };
      })
    };

  isSaving.value = true;
  try {
    const res: any = isEditing.value
      ? await request.put(`/erp/purchase-returns/${route.params.id}`, payload)
      : await request.post('/erp/purchase-returns', payload);

    if (res.data.code === 200) {
      const data = res.data.data || {};
      const savedId = data.order?.id || data.id || Number(route.params.id || 0) || null;
      const savedOrderNo = data.order?.orderNo || data.orderNo || formData.orderNo || '';
      if (!options.silentSuccess) {
        notifySuccess(t('message.saveSuccess'));
      }
      if (!isEditing.value && savedId && options.reloadAfterCreate) {
        await router.replace({
          path: `/erp/purchase-returns/${savedId}/edit`,
          query: { from: 'draft', returnTo: '/erp/purchase-returns/draft' }
        });
        await loadDetail();
      }
      if (options.showPostSaveDialog) {
        openSaveSuccessDialog(savedId, savedOrderNo);
      }
      if (closeOnSuccess) {
        closePage(getReturnPath());
      }
      return savedId;
    }
  } catch (error) {
    notifyError(error);
  } finally {
    isSaving.value = false;
  }
  return null;
};

const parseDecimal = (value: string | number | undefined, scale: number) => {
  if (value == null || value === '') return 0;
  const raw = String(value);
  const normalized = raw.endsWith('.') ? raw.slice(0, -1) : raw;
  if (!normalized) return 0;
  const regex = new RegExp(`^\\d+(\\.\\d{1,${scale}})?$`);
  if (!regex.test(normalized)) {
    return null;
  }
  return Number(normalized);
};

const parseAmount = (value: string) => parseDecimal(value, 2);

const formatDateTime = (date: Date) => {
  const pad = (num: number) => String(num).padStart(2, '0');
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
};

const formatDisplayDateTime = (value?: string) => {
  if (!value) return '-';
  return normalizeDateTimeValue(value) || '-';
};

const normalizeDateTimeValue = (value: any) => {
  if (!value) return '';
  if (value instanceof Date) {
    return formatDateTime(value);
  }
  const raw = String(value);
  if (!raw) return '';
  if (raw.includes('T')) {
    const parsed = new Date(raw);
    if (Number.isNaN(parsed.getTime())) {
      return '';
    }
    return formatDateTime(parsed);
  }
  return raw;
};

