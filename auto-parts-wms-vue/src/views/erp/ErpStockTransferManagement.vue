      <div class="page-toolbar-card">
        <div class="table-toolbar inventory-toolbar">
          <div class="table-filters inventory-filters">
            <el-input
              v-model="searchQuery"
              :placeholder="$t('action.search')"
              class="inventory-field--wide"
              clearable
              @clear="handleSearch"
              @keyup.enter="handleSearch"
            />
            <el-date-picker
              v-model="startAt"
              type="datetime"
              :placeholder="$t('field.startTime')"
              format="YYYY-MM-DD HH:mm:ss"
              value-format="YYYY-MM-DD HH:mm:ss"
              class="inventory-field--date"
              @change="handleSearch"
            />
            <el-date-picker
              v-model="endAt"
              type="datetime"
              :placeholder="$t('field.endTime')"
              format="YYYY-MM-DD HH:mm:ss"
              value-format="YYYY-MM-DD HH:mm:ss"
              class="inventory-field--date"
              @change="handleSearch"
            />
          </div>
          <div class="table-actions inventory-actions">
            <el-button type="primary" v-permission="'erp-stock-count:add'" @click="openAddModal">
              {{ $t('action.add') }}
            </el-button>
          </div>
        </div>
      </div>
    </div>

    <div class="table-card">
      <div class="table-body">
        <el-table
          :data="tableData"
