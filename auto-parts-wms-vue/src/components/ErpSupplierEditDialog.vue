<script setup lang="ts">
import { computed, nextTick, onBeforeUnmount, reactive, ref, Teleport, watch } from 'vue';
import { useI18n } from 'vue-i18n';
import { useApiError } from '@/composables/useApiError';

type SupplierStatus = 'enabled' | 'disabled' | 'blacklisted';

interface CodeOptionItem {
  id?: number;
  code: string;
  name: string;
  isDefault?: boolean;
}

interface CounterpartySubjectOption {
  id: number;
  name: string;
}

interface SupplierFormValue {
  code?: string;
  name?: string;
  shortName?: string;
  supplierTypeId?: number;
  region?: string;
  contact?: string;
  phone?: string;
  mobile?: string;
  wechat?: string;
  purchaser?: string;
  contactInfo?: string;
  businessScope?: string;
  counterpartySubjectId?: number;
  sourceCreatedBy?: string;
  sourceCreatedAt?: string;
  email?: string;
  address?: string;
  taxNo?: string;
  bankName?: string;
  bankAccount?: string;
  defaultSettlementMethodCode?: string;
  defaultPaymentMethodCode?: string;
  contacts?: string | SupplierContactItem[];
  enabled?: boolean;
  blacklisted?: boolean;
  remark?: string;
}

interface SupplierContactItem {
  name?: string;
  phone?: string;
  mobile?: string;
  wechat?: string;
  email?: string;
  remark?: string;
  isPrimary?: boolean;
}

interface SupplierContactMethod {
  value?: string;
  isPrimary?: boolean;
}

interface SupplierContactGroup {
  name?: string;
  wechat?: string;
  email?: string;
  remark?: string;
  isPrimary?: boolean;
  methods: SupplierContactMethod[];
  draftMethod?: string;
}

interface SupplierSubmitPayload {
  code: string;
  name: string;
  shortName?: string;
  supplierTypeId?: number;
  region?: string;
  contact?: string;
  phone?: string;
  mobile?: string;
  wechat?: string;
  purchaser?: string;
  contactInfo?: string;
  businessScope?: string;
  counterpartySubjectId?: number;
  sourceCreatedBy?: string;
  sourceCreatedAt?: string;
  email?: string;
  address?: string;
  taxNo?: string;
  bankName?: string;
  bankAccount?: string;
  defaultSettlementMethodCode?: string;
  defaultPaymentMethodCode?: string;
  contacts?: string;
  enabled: boolean;
  blacklisted: boolean;
  remark?: string;
}

interface DialogViewportBounds {
  minWidth: number;
  maxWidth: number;
  minHeight: number;
  maxHeight: number;
  padding: number;
}

const props = withDefaults(defineProps<{
  modelValue: boolean;
  mode: 'create' | 'edit';
  initialValue?: SupplierFormValue | null;
  supplierTypeOptions: CodeOptionItem[];
  counterpartySubjectOptions: CounterpartySubjectOption[];
  settlementMethodOptions: CodeOptionItem[];
  paymentMethodOptions: CodeOptionItem[];
  nextCode?: string;
  submitting?: boolean;
}>(), {
  initialValue: null,
  nextCode: '',
  submitting: false
});

const emit = defineEmits<{
  (e: 'update:modelValue', value: boolean): void;
  (e: 'submit', value: SupplierSubmitPayload): void;
  (e: 'closed'): void;
}>();

const { t } = useI18n();
const { notifyWarning } = useApiError();

const dialogVisible = computed({
  get: () => props.modelValue,
  set: (value: boolean) => emit('update:modelValue', value)
});
const isEditing = computed(() => props.mode === 'edit');
const financeOptionalExpanded = ref(false);
const historyOptionalExpanded = ref(false);
const supplierNameInputRef = ref<{ focus?: () => void } | null>(null);
const resizeHandleTeleportTarget = ref<HTMLElement | null>(null);
const dialogState = reactive({
  width: 960,
  height: 620,
  top: 48,
  left: 0
});
const activeResizePointerId = ref<number | null>(null);
const resizeState = ref<{
  direction: 'nw' | 'ne' | 'sw' | 'se';
  startX: number;
  startY: number;
  startWidth: number;
  startHeight: number;
  startTop: number;
  startLeft: number;
} | null>(null);

const formData = reactive({
  code: '',
  name: '',
  shortName: '',
  supplierTypeId: undefined as number | undefined,
  region: '',
  purchaser: '',
  contacts: [] as SupplierContactGroup[],
  businessScope: 'SUPPLIER',
  counterpartySubjectId: undefined as number | undefined,
  sourceCreatedBy: '',
  sourceCreatedAt: '',
  email: '',
  address: '',
  taxNo: '',
  bankName: '',
  bankAccount: '',
  defaultSettlementMethodCode: '',
  defaultPaymentMethodCode: '',
  status: 'enabled' as SupplierStatus,
  remark: ''
});

const dialogStyle = computed(() => ({
  '--supplier-dialog-width': `${dialogState.width}px`,
  '--supplier-dialog-height': `${dialogState.height}px`,
  '--supplier-dialog-top': `${dialogState.top}px`,
  '--supplier-dialog-left': `${dialogState.left}px`
}));
const financeToggleLabel = computed(() => (
  financeOptionalExpanded.value ? t('supplierDialog.collapseOptional') : t('supplierDialog.expandOptional')
));
const historyToggleLabel = computed(() => (
  historyOptionalExpanded.value ? t('supplierDialog.collapseOptional') : t('supplierDialog.expandOptional')
));
const formatSourceCreatedAtDisplay = (value?: string) => {
  if (!value) return '';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat('zh-CN', {
    timeZone: 'Asia/Shanghai',
    hour12: false,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit'
  }).format(date);
};
const sourceCreatedAtDisplay = computed(() => formatSourceCreatedAtDisplay(formData.sourceCreatedAt));

const resetForm = () => {
  formData.code = '';
  formData.name = '';
  formData.shortName = '';
  formData.supplierTypeId = undefined;
  formData.region = '';
  formData.purchaser = '';
  formData.contacts = [];
  formData.businessScope = 'SUPPLIER';
  formData.counterpartySubjectId = undefined;
  formData.sourceCreatedBy = '';
  formData.sourceCreatedAt = '';
  formData.email = '';
  formData.address = '';
  formData.taxNo = '';
  formData.bankName = '';
  formData.bankAccount = '';
  formData.defaultSettlementMethodCode = '';
  formData.defaultPaymentMethodCode = '';
  formData.status = 'enabled';
  formData.remark = '';
  financeOptionalExpanded.value = false;
  historyOptionalExpanded.value = false;
};

const resolveStatus = (value?: SupplierFormValue): SupplierStatus => {
  if (value?.blacklisted) return 'blacklisted';
  return value?.enabled === false ? 'disabled' : 'enabled';
};

const applyDefaultMethods = () => {
  if (isEditing.value) return;
  if (!formData.defaultSettlementMethodCode && props.settlementMethodOptions.length) {
    const defaultItem = props.settlementMethodOptions.find(item => item.isDefault) ?? props.settlementMethodOptions[0];
    if (defaultItem) {
      formData.defaultSettlementMethodCode = defaultItem.code;
    }
  }
  if (!formData.defaultPaymentMethodCode && props.paymentMethodOptions.length) {
    const defaultItem = props.paymentMethodOptions.find(item => item.isDefault) ?? props.paymentMethodOptions[0];
    if (defaultItem) {
      formData.defaultPaymentMethodCode = defaultItem.code;
    }
  }
};

const applyInitialValue = () => {
  resetForm();
  if (!isEditing.value) {
    formData.code = props.nextCode || '';
    formData.contacts = [{ isPrimary: true, methods: [{}] }];
    applyDefaultMethods();
    return;
  }

  const row = props.initialValue;
  if (!row) return;
  formData.code = row.code || '';
  formData.name = row.name || '';
  formData.shortName = row.shortName || '';
  formData.supplierTypeId = row.supplierTypeId;
  formData.region = row.region || '';
  formData.purchaser = row.purchaser || '';
  formData.contacts = buildInitialContacts(row);
  formData.businessScope = row.businessScope || 'SUPPLIER';
  formData.counterpartySubjectId = row.counterpartySubjectId;
  formData.sourceCreatedBy = row.sourceCreatedBy || '';
  formData.sourceCreatedAt = row.sourceCreatedAt || '';
  formData.email = row.email || '';
  formData.address = row.address || '';
  formData.taxNo = row.taxNo || '';
  formData.bankName = row.bankName || '';
  formData.bankAccount = row.bankAccount || '';
  formData.defaultSettlementMethodCode = row.defaultSettlementMethodCode || '';
  formData.defaultPaymentMethodCode = row.defaultPaymentMethodCode || '';
  formData.status = resolveStatus(row);
  formData.remark = row.remark || '';
};

const parseContacts = (raw?: unknown): SupplierContactItem[] => {
  if (!raw) return [];
  if (Array.isArray(raw)) return raw as SupplierContactItem[];
  if (typeof raw === 'string') {
    try {
      const parsed = JSON.parse(raw);
      return Array.isArray(parsed) ? parsed as SupplierContactItem[] : [];
    } catch {
      return [];
    }
  }
  return [];
};

const addContact = () => {
  if (!formData.contacts.length) {
    formData.contacts.push({ isPrimary: true, methods: [], draftMethod: '' });
    return;
  }
  formData.contacts.push({ isPrimary: false, methods: [], draftMethod: '' });
};

const removeContact = (groupIndex: number) => {
  const removed = formData.contacts[groupIndex];
  formData.contacts.splice(groupIndex, 1);
  if (!formData.contacts.length) {
    formData.contacts.push({ isPrimary: true, methods: [], draftMethod: '' });
    return;
  }
  if (removed?.isPrimary && formData.contacts.length) {
    const firstContact = formData.contacts[0];
    if (firstContact) {
      firstContact.isPrimary = true;
    }
  }
};

const splitContactValues = (raw?: string) => (
  raw
    ?.split(/[\n,，;；]+/)
    .map(item => item.trim())
    .filter(Boolean) ?? []
);

const ensurePrimaryMethod = (group: SupplierContactGroup) => {
  if (!group.methods.length) {
    return;
  }
  if (!group.methods.some(method => method.isPrimary)) {
    const firstMethod = group.methods[0];
    if (firstMethod) {
      firstMethod.isPrimary = true;
    }
  }
};

const removeContactMethod = (groupIndex: number, methodIndex: number) => {
  const group = formData.contacts[groupIndex];
  if (!group) return;
  const removed = group.methods[methodIndex];
  group.methods.splice(methodIndex, 1);
  if (removed?.isPrimary && group.methods.length) {
    const firstMethod = group.methods[0];
    if (firstMethod) {
      firstMethod.isPrimary = true;
    }
  }
};

const setPrimaryContact = (index: number) => {
  formData.contacts.forEach((group, itemIndex) => {
    group.isPrimary = itemIndex === index;
  });
};

const commitContactMethod = (groupIndex: number) => {
  const group = formData.contacts[groupIndex];
  if (!group) return;
  const values = splitContactValues(group.draftMethod);
  if (!values.length) {
    group.draftMethod = '';
    return;
  }
  const existing = new Set(group.methods.map(method => method.value?.trim()).filter(Boolean));
  values.forEach((value) => {
    if (existing.has(value)) return;
    group.methods.push({
      value,
      isPrimary: group.methods.length === 0
    });
  });
  ensurePrimaryMethod(group);
  group.draftMethod = '';
};

const setPrimaryMethod = (groupIndex: number, methodIndex: number) => {
  const group = formData.contacts[groupIndex];
  if (!group) return;
  group.methods.forEach((method, index) => {
    method.isPrimary = index === methodIndex;
  });
};

const buildInitialContacts = (row: SupplierFormValue): SupplierContactGroup[] => {
  const parsed = parseContacts(row.contacts);
  if (parsed.length) {
    const grouped = new Map<string, SupplierContactGroup>();
    parsed.forEach((item, index) => {
      const key = [
        item.name || '',
        item.wechat || '',
        item.email || '',
        item.remark || ''
      ].join('||');
      let group = grouped.get(key);
      if (!group) {
        group = {
          name: item.name || '',
          wechat: item.wechat || '',
          email: item.email || '',
          remark: item.remark || '',
          isPrimary: !!item.isPrimary || index === 0,
          methods: [],
          draftMethod: ''
        };
        grouped.set(key, group);
      }
      if (item.isPrimary) {
        group.isPrimary = true;
      }
      group.methods.push({
        value: item.mobile || item.phone || '',
        isPrimary: !!item.isPrimary
      });
    });
    const normalized = Array.from(grouped.values()).map((group, index) => ({
      ...group,
      methods: group.methods,
      draftMethod: '',
      isPrimary: group.isPrimary || index === 0
    }));
    if (!normalized.some(item => item.isPrimary) && normalized.length) {
      const firstGroup = normalized[0];
      if (firstGroup) {
        firstGroup.isPrimary = true;
      }
    }
    normalized.forEach(ensurePrimaryMethod);
    return normalized;
  }
  if (row.contact || row.phone || row.mobile || row.wechat || row.email || row.contactInfo) {
    return [{
      name: row.contact || '',
      wechat: row.wechat || '',
      email: row.email || '',
      remark: row.contactInfo || '',
      isPrimary: true,
      methods: [{
        value: row.mobile || row.phone || '',
        isPrimary: true
      }],
      draftMethod: ''
    }];
  }
  return [{ isPrimary: true, methods: [], draftMethod: '' }];
};

const isMobileLike = (value?: string) => /^1\d{10}$/.test(value?.trim() || '');

const buildContactsPayload = () => {
  const contacts = formData.contacts
    .flatMap((group, groupIndex) => {
      const hasPrimary = formData.contacts.some(contact => contact.isPrimary);
      return group.methods.map((method, methodIndex) => ({
        name: group.name?.trim() || '',
        phone: isMobileLike(method.value) ? '' : method.value?.trim() || '',
        mobile: isMobileLike(method.value) ? method.value?.trim() || '' : '',
        wechat: group.wechat?.trim() || '',
        email: group.email?.trim() || '',
        remark: group.remark?.trim() || '',
        isPrimary: ((!!group.isPrimary || (groupIndex === 0 && !hasPrimary)) && !!method.isPrimary)
          || ((!!group.isPrimary || (groupIndex === 0 && !hasPrimary)) && methodIndex === 0 && !group.methods.some(item => item.isPrimary))
      }));
    })
    .filter(item => item.name || item.phone || item.mobile || item.wechat || item.email || item.remark);
  return contacts.length ? JSON.stringify(contacts) : undefined;
};

const getPrimaryContact = () => {
  const contacts = formData.contacts
    .map(group => ({
      name: group.name?.trim() || '',
      phone: isMobileLike(group.methods[0]?.value) ? '' : group.methods[0]?.value?.trim() || '',
      mobile: isMobileLike(group.methods[0]?.value) ? group.methods[0]?.value?.trim() || '' : '',
      wechat: group.wechat?.trim() || '',
      email: group.email?.trim() || '',
      remark: group.remark?.trim() || '',
      isPrimary: !!group.isPrimary
    }))
    .filter(item => item.name || item.phone || item.mobile || item.wechat || item.email || item.remark);
  if (!contacts.length) {
    return null;
  }
  return contacts.find(item => item.isPrimary) || contacts[0];
};

const buildContactInfoSummary = () => {
  const contacts = formData.contacts
    .map(group => ({
      name: group.name?.trim() || '',
      wechat: group.wechat?.trim() || '',
      email: group.email?.trim() || '',
      remark: group.remark?.trim() || '',
      phones: group.methods
        .map(method => method.value?.trim() || '')
        .filter(Boolean)
    }))
    .filter(item => item.name || item.wechat || item.email || item.remark || item.phones.length);
  if (!contacts.length) {
    return undefined;
  }
  return contacts.map((item) => [
    item.name,
    item.phones.join('；'),
    item.wechat ? `微信:${item.wechat}` : '',
    item.email,
    item.remark
  ].filter(Boolean).join(' / ')).join('；');
};

