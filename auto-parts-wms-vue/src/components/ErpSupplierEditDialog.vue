const getViewportDialogBounds = (): DialogViewportBounds => {
  if (typeof window === 'undefined') {
    return {
      minWidth: dialogState.width,
      maxWidth: dialogState.width,
      minHeight: dialogState.height,
      maxHeight: dialogState.height,
      padding: 0
    };
  }

  const padding = 16;
  const minWidth = Math.min(680, window.innerWidth - padding * 2);
  const maxWidth = Math.max(minWidth, window.innerWidth - padding * 2);
  const minHeight = Math.min(520, window.innerHeight - padding * 2);
  const maxHeight = Math.max(minHeight, window.innerHeight - padding * 2);

  return {
    minWidth: Math.max(320, minWidth),
    maxWidth,
    minHeight: Math.max(420, minHeight),
    maxHeight,
    padding
  };
};

const applyDialogBounds = (
  nextWidth: number,
  nextHeight: number,
  nextTop: number,
  nextLeft: number
) => {
  if (typeof window === 'undefined') return;
  const { minWidth, maxWidth, minHeight, maxHeight, padding } = getViewportDialogBounds();
  const width = Math.min(Math.max(nextWidth, minWidth), maxWidth);
  const height = Math.min(Math.max(nextHeight, minHeight), maxHeight);
  const maxLeft = Math.max(padding, window.innerWidth - width - padding);
  const maxTop = Math.max(padding, window.innerHeight - height - padding);

  dialogState.width = Math.round(width);
  dialogState.height = Math.round(height);
  dialogState.left = Math.round(Math.min(Math.max(nextLeft, padding), maxLeft));
  dialogState.top = Math.round(Math.min(Math.max(nextTop, padding), maxTop));
};

const centerDialog = () => {
  if (typeof window === 'undefined') return;
  const { maxWidth, maxHeight } = getViewportDialogBounds();
  const width = Math.min(960, maxWidth);
  const height = Math.min(620, maxHeight);
  const left = Math.max(16, Math.round((window.innerWidth - width) / 2));
  const top = Math.max(24, Math.round((window.innerHeight - height) / 2) - 24);
  applyDialogBounds(width, height, top, left);
};

const clearResizeListeners = () => {
  if (typeof window === 'undefined') return;
  window.removeEventListener('pointermove', handleResizePointerMove);
  window.removeEventListener('pointerup', stopResize);
  window.removeEventListener('pointercancel', stopResize);
};

const resolveDialogElement = () => document.querySelector('.el-dialog.supplier-dialog') as HTMLElement | null;

const updateResizeHandleTeleportTarget = () => {
  if (typeof window === 'undefined') return;
  resizeHandleTeleportTarget.value = resolveDialogElement();
};

const syncDialogPositionFromTransform = () => {
  if (typeof window === 'undefined') return;
  const dialogElement = resolveDialogElement();
  if (!dialogElement) return;
  const computedStyle = window.getComputedStyle(dialogElement);
  const transform = computedStyle.transform;
  if (!transform || transform === 'none') return;

  const matrix = new DOMMatrixReadOnly(transform);
  if (!matrix.m41 && !matrix.m42) return;

  applyDialogBounds(
    dialogState.width,
    dialogState.height,
    dialogState.top + matrix.m42,
    dialogState.left + matrix.m41
  );
  dialogElement.style.transform = 'none';
};

const syncDialogStateFromDom = () => {
  if (typeof window === 'undefined') return;
  const dialogElement = resolveDialogElement();
  if (!dialogElement) return;
  const rect = dialogElement.getBoundingClientRect();
  applyDialogBounds(rect.width, rect.height, rect.top, rect.left);
};

const startResize = (direction: 'nw' | 'ne' | 'sw' | 'se', event: PointerEvent) => {
  event.preventDefault();
  event.stopPropagation();
  syncDialogPositionFromTransform();
  syncDialogStateFromDom();
  activeResizePointerId.value = event.pointerId;
  resizeState.value = {
    direction,
    startX: event.clientX,
    startY: event.clientY,
    startWidth: dialogState.width,
    startHeight: dialogState.height,
    startTop: dialogState.top,
    startLeft: dialogState.left
  };
  window.addEventListener('pointermove', handleResizePointerMove);
  window.addEventListener('pointerup', stopResize);
  window.addEventListener('pointercancel', stopResize);
};

const handleResizePointerMove = (event: PointerEvent) => {
  if (!resizeState.value) return;
  if (activeResizePointerId.value !== null && event.pointerId !== activeResizePointerId.value) return;

  const deltaX = event.clientX - resizeState.value.startX;
  const deltaY = event.clientY - resizeState.value.startY;
  let width = resizeState.value.startWidth;
  let height = resizeState.value.startHeight;
  let top = resizeState.value.startTop;
  let left = resizeState.value.startLeft;

  if (resizeState.value.direction.includes('e')) {
    width = resizeState.value.startWidth + deltaX;
  }
  if (resizeState.value.direction.includes('s')) {
    height = resizeState.value.startHeight + deltaY;
  }
  if (resizeState.value.direction.includes('w')) {
    width = resizeState.value.startWidth - deltaX;
    left = resizeState.value.startLeft + deltaX;
  }
  if (resizeState.value.direction.includes('n')) {
    height = resizeState.value.startHeight - deltaY;
    top = resizeState.value.startTop + deltaY;
  }

  applyDialogBounds(width, height, top, left);
};

const stopResize = (event?: PointerEvent) => {
  if (
    event &&
    activeResizePointerId.value !== null &&
    event.pointerId !== activeResizePointerId.value
  ) {
    return;
  }
  resizeState.value = null;
  activeResizePointerId.value = null;
  clearResizeListeners();
};

